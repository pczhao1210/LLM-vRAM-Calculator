export function getQuantizationById(id: string): QuantizationPreset {
  return quantizationCatalog.find((item) => item.id === id) ?? quantizationCatalog[0]
}

export function getModelById(id: string): ModelPreset {
  return modelCatalog.find((item) => item.id === id) ?? modelCatalog[0]
}

export function getGpuById(id: string): GpuProfile {
  return gpuCatalog.find((item) => item.id === id) ?? gpuCatalog[0]
}

function hasRequiredGpuFeatures(gpu: GpuProfile, quantizationId: string): boolean {
  const quantization = getQuantizationById(quantizationId)
  const requiredFeatures = quantization.requiredGpuFeatures ?? []

  if (requiredFeatures.length === 0) {
    return true
  }

  const supportedFeatures = new Set(gpu.supportedGpuFeatures ?? [])
  return requiredFeatures.every((feature) => supportedFeatures.has(feature))
}

export function getGpuQuantizationSupportLevel(gpu: GpuProfile, quantizationId: string): QuantizationSupportLevel {
  if (!hasRequiredGpuFeatures(gpu, quantizationId)) {
    return 'notRecommended'
  }

  switch (quantizationId) {
    case 'fp8':
      return 'supported'

    case 'int8':
      return gpu.deploymentTier === 'datacenter' || gpu.generationRank >= 3 ? 'supported' : 'conditional'

    case 'int4-awq':
      return gpu.deploymentTier === 'datacenter' || gpu.memoryPerUnitGB >= 48 ? 'supported' : 'conditional'

    case 'gguf-q8':
    case 'gguf-q6':
    case 'gguf-q4km':
      if (gpu.category === 'platform') {
        return 'notRecommended'
      }

      return gpu.deploymentTier === 'workstation' ? 'supported' : 'conditional'

    default:
      return 'supported'
  }
}

export function doesGpuSupportQuantization(gpu: GpuProfile, quantizationId: string): boolean {
  return getGpuQuantizationSupportLevel(gpu, quantizationId) !== 'notRecommended'
}

export function getSupportedQuantizationsForGpu(gpu: GpuProfile): QuantizationPreset[] {
  return quantizationCatalog.filter((item) => doesGpuSupportQuantization(gpu, item.id))
}

export function resolveCompatibleQuantizationId(gpu: GpuProfile, preferredIds: string[]): string {
  const supportedQuantizations = getSupportedQuantizationsForGpu(gpu)

  for (const id of preferredIds) {
    if (supportedQuantizations.some((item) => item.id === id)) {
      return id
    }
  }

  return supportedQuantizations[0]?.id ?? quantizationCatalog[0].id
}
